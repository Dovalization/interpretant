print("\nPlot 5: influence graph…")

GRAPH_DECADES = [1880, 1940, 1990, 2020]
GRAPH_TOPN = 15

fig5, axes5 = plt.subplots(1, 4, figsize=(22, 7), facecolor=C_BG)
fig5.subplots_adjust(left=0.02, right=0.98, top=0.86, bottom=0.06, wspace=0.10)
fig5.text(0.06, 0.97, "interpretant", color=C_DARK, fontproperties=fp("Bold", 16), va="top")
fig5.text(
    0.06, 0.942,
    "Semantic influence graph  ·  bridge concepts connecting contested vocabularies per era",
    color=C_MID, fontproperties=fp("Regular", 10), va="top",
)

for ax, decade in zip(axes5, GRAPH_DECADES):
    ax.set_facecolor(C_BG)
    ax.axis("off")
    ax.set_title(f"{decade}s", color=C_DARK, fontproperties=fp("Bold", 11), pad=8)

    word_nb: dict[str, set[str]] = {
        word: set(get_real_neighbors(word, decade, GRAPH_TOPN))
        for word in TARGET_WORDS
    }

    bridge_count: Counter[str] = Counter()
    for nb_set in word_nb.values():
        for nb_word in nb_set:
            bridge_count[nb_word] += 1

    # Include all bridges — attributed and unattributed (R3)
    bridges = [w for w, c in bridge_count.items() if c >= 2]

    if not bridges:
        ax.text(0.5, 0.5, "no bridge concepts", ha="center", va="center",
                transform=ax.transAxes, color=C_MID,
                fontproperties=fp("Regular", 9))
        continue

    # ── Bipartite fixed layout (R7) ───────────────────────────────────────────
    # Target words: evenly spaced at y=1.0
    n_targets = len(TARGET_WORDS)
    target_pos: dict[str, tuple[float, float]] = {
        word: (i / max(n_targets - 1, 1), 1.0)
        for i, word in enumerate(TARGET_WORDS)
    }

    # Bridge nodes: y=0.0, grouped by field (fields left to right, unattributed last)
    _field_order_graph = list(FIELDS.keys()) + ["Unattributed"]
    field_groups_graph: dict[str, list[str]] = {f: [] for f in _field_order_graph}
    for bridge in bridges:
        field_groups_graph[word_field(bridge)].append(bridge)
    for f in _field_order_graph:
        field_groups_graph[f].sort(key=lambda w: -bridge_count[w])

    ordered_bridges: list[str] = []
    for f in _field_order_graph:
        ordered_bridges.extend(field_groups_graph[f])

    n_bridges = len(ordered_bridges)
    bridge_pos: dict[str, tuple[float, float]] = {
        bridge: (i / max(n_bridges - 1, 1), 0.0)
        for i, bridge in enumerate(ordered_bridges)
    }

    # Draw edges
    for word in TARGET_WORDS:
        tx, ty = target_pos[word]
        for bridge in ordered_bridges:
            if bridge in word_nb[word]:
                bx, by = bridge_pos[bridge]
                ax.plot([tx, bx], [ty, by], color=C_SPINE, alpha=0.22,
                        linewidth=bridge_count[bridge] * 0.5, zorder=1)

    # Draw bridge nodes
    for bridge in ordered_bridges:
        bx, by = bridge_pos[bridge]
        f = word_field(bridge)
        color = FIELD_COLORS.get(f, FIELD_COLORS["Unattributed"])
        size = max(20, 50 + bridge_count[bridge] * 20)
        ax.scatter(bx, by, color=color, s=size, alpha=0.80, zorder=3)
        ax.text(bx, by - 0.04, bridge, ha="center", va="top",
                color=color, fontproperties=fp("Regular", 5.5), zorder=4, clip_on=False)

    # Draw target nodes
    for word in TARGET_WORDS:
        tx, ty = target_pos[word]
        ax.scatter(tx, ty, color=WORD_COLOR[word], s=500, alpha=0.95, zorder=5)
        ax.text(tx, ty, word, ha="center", va="center",
                color="white", fontproperties=fp("Bold", 7.5), zorder=6)

    # Add a subtle field band behind bridge layer for visual grouping
    for f in _field_order_graph:
        grp = field_groups_graph[f]
        if not grp:
            continue
        _x_left = bridge_pos[grp[0]][0] - 0.03
        _x_right = bridge_pos[grp[-1]][0] + 0.03
        ax.axvspan(_x_left, _x_right, ymin=0.0, ymax=0.15,
                   color=FIELD_COLORS.get(f, FIELD_COLORS["Unattributed"]),
                   alpha=0.08, zorder=0)

    ax.set_xlim(-0.08, 1.08)
    ax.set_ylim(-0.35, 1.20)

