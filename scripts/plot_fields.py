def is_real_word(w: str) -> bool:
    """True if w is a lowercase alphabetic word present in the English dictionary
    or in our field lexicons.  Filters out model names, abbreviations, and
    numeric/punctuation tokens."""
    return bool(re.match(r"^[a-z]{4,}$", w)) and w in _valid_words


# ─── Centroid-based field attribution ────────────────────────────────────────

# Cache field centroids per decade
_centroid_cache: dict[tuple[str, int], np.ndarray | None] = {}


def _field_centroid(fname: str, decade: int) -> np.ndarray | None:
    key = (fname, decade)
    if key not in _centroid_cache:
        kv = get_kv(decade)
        if kv is None:
            _centroid_cache[key] = None
        else:
            available = [w for w in FIELDS[fname] if w in kv]
            if len(available) < 3:
                _centroid_cache[key] = None
            else:
                c = np.mean([kv[w] for w in available], axis=0).astype(np.float32)
                norm = np.linalg.norm(c)
                _centroid_cache[key] = c / norm if norm > 1e-9 else None
    return _centroid_cache[key]


def word_field_centroid(word: str, decade: int) -> str:
    """Dominant field for a word in a given decade via centroid proximity."""
    kv = get_kv(decade)
    if kv is None or word not in kv:
        return "Unattributed"
    wv = kv[word].astype(np.float32)
    wn = np.linalg.norm(wv)
    if wn < 1e-9:
        return "Unattributed"
    wv = wv / wn
    best_field, best_sim = "Unattributed", -1.0
    for fname in FIELDS:
        centroid = _field_centroid(fname, decade)
        if centroid is None:
            continue
        sim = float(np.dot(wv, centroid))
        if sim > best_sim:
            best_sim, best_field = sim, fname
    return best_field


# ─── KV cache ─────────────────────────────────────────────────────────────────

KV_DIR = pathlib.Path("models/twec")
_kv_cache: dict[int, KeyedVectors] = {}


def get_kv(decade: int) -> KeyedVectors | None:
    if decade not in _kv_cache:
        path = KV_DIR / f"{decade}.kv"
        if path.exists():
            _kv_cache[decade] = KeyedVectors.load(str(path))
    return _kv_cache.get(decade)


def get_neighbors_raw(word: str, decade: int, topn: int = 80) -> list[tuple[str, float]]:
    kv = get_kv(decade)
    if kv is None or word not in kv:
        return []
    return kv.most_similar(word, topn=topn)


def get_real_neighbors(word: str, decade: int, topn: int = 20) -> list[str]:
    raw = get_neighbors_raw(word, decade, topn * 5)
    return [w for w, _ in raw if is_real_word(w)][:topn]


