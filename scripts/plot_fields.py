for ax, word in zip(axes4, TARGET_WORDS):
    retained_vals: list[float] = []
    entered_vals: list[float] = []
    exited_vals: list[float] = []
    entered_by_field: dict[str, list[float]] = {f: [] for f in _churn_fields + ["Unattributed"]}
    exited_by_field: dict[str, list[float]] = {f: [] for f in _churn_fields + ["Unattributed"]}

    for t0, t1 in zip(all_decades, all_decades[1:]):
        nb0 = set(get_real_neighbors(word, t0, CHURN_TOPN))
        nb1 = set(get_real_neighbors(word, t1, CHURN_TOPN))
        denom = CHURN_TOPN
        entered_words = nb1 - nb0
        exited_words = nb0 - nb1
        retained_vals.append(len(nb0 & nb1) / denom)
        entered_vals.append(len(entered_words) / denom)
        exited_vals.append(len(exited_words) / denom)
        for f in _churn_fields + ["Unattributed"]:
            entered_by_field[f].append(sum(1 for w in entered_words if word_field(w) == f) / denom)
            exited_by_field[f].append(sum(1 for w in exited_words if word_field(w) == f) / denom)

    xi = range(len(transitions))

    # Retained: solid
    ax.bar(xi, retained_vals, color=churn_colors["retained"], alpha=0.82, width=0.55, label="retained")

    # Entered (above 0): stacked by field colour
    bottom_pos = list(retained_vals)
    for f in _churn_fields + ["Unattributed"]:
        vals = entered_by_field[f]
        ax.bar(xi, vals, bottom=bottom_pos, color=FIELD_COLORS[f], alpha=0.82, width=0.55)
        bottom_pos = [b + v for b, v in zip(bottom_pos, vals)]

    # Exited (below 0): stacked by field colour
    bottom_neg = [0.0] * len(transitions)
    for f in _churn_fields + ["Unattributed"]:
        vals = exited_by_field[f]
        ax.bar(xi, [-v for v in vals], bottom=bottom_neg, color=FIELD_COLORS[f], alpha=0.65, width=0.55)
        bottom_neg = [b - v for b, v in zip(bottom_neg, vals)]

