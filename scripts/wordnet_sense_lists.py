"""Round Z's sense lists: DWUG EN's 46 words with senses taken mechanically from WordNet 3.0.

For each word, the WordNet synsets of its part of speech that contain the word itself as a lemma,
in WordNet's order (most frequent in its sense-tagged corpus first), the first four kept, the cap
round Y's lists had. Instance synsets (named individuals, such as Sir Hiram Maxim under *maxim*)
are left out: they name people and places, not senses of the word. That rule was added after a
first generation showed two of them, before any usage was labelled. A sense's key is made from
the synset's other lemma names (up to two), or, when it has none, from the first three words of
its definition; its definition and first example are WordNet's. No sense is chosen, worded or
reordered by hand.

    uv run --extra labels python scripts/wordnet_sense_lists.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from nltk.corpus import wordnet

ROOT = Path("data/external/dwug_en_2.0.1/dwug_en/data")
OUT = Path("data/sense_lists/dwug_en_wordnet.toml")
CAP = 4
NO_EXAMPLE = "no example in WordNet"


def slug(words: list[str]) -> str:
    return "_".join(re.sub(r"[^a-z0-9]+", "_", w.lower()).strip("_") for w in words if w)


def senses(word: str, pos: str) -> list[tuple[str, str, str]]:
    found = []
    used: set[str] = set()
    for synset in wordnet.synsets(word, pos=pos):
        if synset.instance_hypernyms():
            continue
        names = [lemma.name() for lemma in synset.lemmas()]
        if word not in (name.lower() for name in names):
            continue
        others = [name for name in names if name.lower() != word]
        key = slug(others[:2]) if others else slug(synset.definition().split()[:3])
        key = key or slug([word, str(len(found) + 1)])
        while key in used:
            key = f"{key}_{len(found) + 1}"
        used.add(key)
        examples = synset.examples()
        found.append((key, synset.definition(), examples[0] if examples else NO_EXAMPLE))
        if len(found) == CAP:
            break
    return found


def main() -> None:
    lines = [
        "# Round Z's sense lists (docs/predictions_labels.md), generated by",
        f"# scripts/wordnet_sense_lists.py from WordNet {wordnet.get_version()};",
        "# not edited by hand.",
        "",
    ]
    for path in sorted(ROOT.iterdir()):
        lemma = path.name
        word, part = lemma.rsplit("_", 1)
        found = senses(word, {"nn": "n", "vb": "v"}[part])
        lines += [f"[{lemma}]", f"word = {json.dumps(word)}"]
        for key, definition, example in found:
            lines += [
                f"[[{lemma}.senses]]",
                f"key = {json.dumps(key)}",
                f"definition = {json.dumps(definition)}",
                f"example = {json.dumps(example)}",
            ]
        lines.append("")
        print(f"{lemma}: {len(found)} senses: {', '.join(key for key, _, _ in found)}")
    OUT.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
